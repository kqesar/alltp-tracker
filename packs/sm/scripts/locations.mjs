// Regenerates src/locations.ts: Map Rando's 100 item locations and the bit of
// each in the game's collected-items array. The ROM is not in CI, so the
// output is committed and this runs by hand, like the other importers.
//
//   pnpm --filter @alltp/pack-sm import-locations <sm-json-data checkout> <vanilla.sfc>
//
// A location is an sm-json-data node with `nodeType: "item"`, keyed by its
// `room_id:node_id` as the spoiler log gives it (rust/maprando-game/src/lib.rs:
// 4908-4914 lists them the same way). Its `nodeAddress` is the PC address of
// the item's PLM in the vanilla ROM; the word at PLM + 4 is the bit it sets in
// the array at $7E:D870 (rust/maprando/src/patch.rs:843-866 reads it from
// there and rewrites only the PLM's type, never its argument).
//
// The checkout is untrusted data: this reads its JSON and runs nothing of it.
// The ROM is the Super Metroid (Japan, USA) one, headerless, checked by hash.

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const VANILLA_SHA256 =
  "12b77c4bc9c1832cee8881244659065ee1d84c70c3d29e6eaf92e6798cc2ca72";
const BITS = 160;
const EXPECTED = 100;

const [checkout, romPath] = process.argv.slice(2);
if (!checkout || !romPath) {
  console.error("usage: locations.mjs <sm-json-data checkout> <vanilla.sfc>");
  process.exit(2);
}

const rom = readFileSync(romPath);
const sha = createHash("sha256").update(rom).digest("hex");
if (sha !== VANILLA_SHA256) {
  console.error(`${romPath} is not the headerless vanilla ROM (sha256 ${sha})`);
  process.exit(1);
}

const jsonFiles = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (entry.isDirectory()) return jsonFiles(join(dir, entry.name));
    return entry.name.endsWith(".json") ? [join(dir, entry.name)] : [];
  });

const rows = [];
for (const file of jsonFiles(join(checkout, "region"))) {
  const room = JSON.parse(readFileSync(file, "utf8"));
  if (!Array.isArray(room.nodes)) continue;
  for (const node of room.nodes) {
    if (node.nodeType !== "item") continue;
    const address = Number.parseInt(node.nodeAddress, 16);
    const bit = rom[address + 4] | (rom[address + 5] << 8);
    rows.push({ bit, key: `${room.id}:${node.id}` });
  }
}
rows.sort((a, b) => {
  const [ar, an] = a.key.split(":").map(Number);
  const [br, bn] = b.key.split(":").map(Number);
  return ar - br || an - bn;
});

const bits = new Set(rows.map((row) => row.bit));
if (
  rows.length !== EXPECTED ||
  new Set(rows.map((row) => row.key)).size !== EXPECTED ||
  bits.size !== EXPECTED ||
  rows.some((row) => row.bit >= BITS)
) {
  console.error(
    `expected ${EXPECTED} locations with distinct bits below ${BITS}, got ${rows.length} (${bits.size} bits)`,
  );
  process.exit(1);
}

const out = `// Map Rando's ${EXPECTED} item locations and the bit each sets in the game's
// collected-items array at $7E:D870, which memory.ts reads. Generated by
// scripts/locations.mjs, never edited by hand: it reads sm-json-data's item
// nodes (their \`nodeAddress\` is the item's PLM in the vanilla ROM) and the
// word at that PLM + 4. The table is the same for every seed: the patcher
// rewrites a PLM's type, never its argument (patch.rs:843-866).
//
// Bit i is byte $7E:D870 + (i >> 3), mask 1 << (i & 7). A key is the spoiler
// log's \`room_id:node_id\`, as Placement.location has it.

/** Every item location, by the log's room and node ids. */
export const LOCATIONS = [
${rows.map((row) => `  { bit: ${row.bit}, key: "${row.key}" },`).join("\n")}
] as const;

/** A location's key: \`room_id:node_id\`. */
export type LocationKey = (typeof LOCATIONS)[number]["key"];

/** Every location key, in the log's order (room, then node). */
export const LOCATION_KEYS = LOCATIONS.map((location) => location.key) as [
  LocationKey,
  ...LocationKey[],
];
`;

writeFileSync(
  join(dirname(fileURLToPath(import.meta.url)), "../src/locations.ts"),
  out,
);
console.log(`wrote ${rows.length} locations`);
